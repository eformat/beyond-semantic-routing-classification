//! `llm_d_sc` — a Praxis HTTP filter for smart multi-turn LLM routing.
//!
//! The filter extracts the prompt from an OpenAI-shaped request body, asks
//! [llm-d-sc] to classify it over the existing `classify.Classify` gRPC
//! contract, and maps the winning ranked label to a MaaS model path. llm-d-sc
//! stays a signal producer; the filter publishes the resolved model as
//! `llm_d_sc.model` metadata, which a downstream praxis `json_body` filter
//! rewrites into the request body (`model` field) for MaaS body-based routing
//! at a single endpoint.
//!
//! See the repo docs for the full contract. The short version:
//!
//! * the filter itself never mutates the body — model selection is published as
//!   `llm_d_sc.model` metadata + the `x-llm-d-sc-model` header, and the stock
//!   `json_body` filter performs the rewrite;
//! * the default posture is fail-open (`default_cluster`, optionally
//!   `default_model`) on every classifier failure, because a classifier outage
//!   should degrade routing quality, not take the gateway down;
//! * client-supplied `x-llm-d-sc-*` headers are stripped on every path, so a
//!   caller can never forge provenance.
//!
//! ```yaml
//! - filter: llm_d_sc
//!   endpoint: "llm-d-sc.beyond-routing.svc.cluster.local:50051"
//!   default_cluster: maas
//!   default_model: publishers/prelude-maas/models/llama-32-3b
//!   routes:
//!     - { label: SIMPLE,  cluster: maas, model: publishers/prelude-maas/models/llama-32-3b }
//!     - { label: COMPLEX, cluster: maas, model: publishers/prelude-maas/models/qwen38-27b }
//! ```
//!
//! [llm-d-sc]: https://github.com/llm-d/llm-d-sc

